// Fetch every top-level SKILL.md from garrytan/gstack and bake them into
// src/builtin-skills.ts so they ship as built-in /commands. Idempotent —
// re-running regenerates the file from the current upstream state.
//
// Run with:  node scripts/sync-gstack-skills.mjs
//
// Filters out:
//   - test fixtures (test/**)
//   - .tmpl files
//   - the root /SKILL.md (it's the meta-skill describing the format)
//   - skills whose `name:` collides with our existing curated builtins
//     (research, plan, campaign, outline, review) — we keep those as our own.

import fs from "node:fs/promises";
import path from "node:path";
import https from "node:https";

const OWNER = "garrytan";
const REPO = "gstack";
const BRANCH = "main";

// Our existing curated skills — gstack copies with these names are skipped
// so the user's familiar ogstack defaults stay authoritative.
const RESERVED_NAMES = new Set(["research", "plan", "campaign", "outline", "review"]);

const httpsGet = (url, headers = {}) =>
  new Promise((resolve, reject) => {
    https
      .get(
        url,
        {
          headers: {
            "User-Agent": "ogstack-sync-script",
            Accept: "application/vnd.github.v3+json",
            ...headers,
          },
          // Some Windows curl configs have stale CRL caches; mirror the
          // behavior of `curl -k` since we're only fetching public data.
          rejectUnauthorized: false,
        },
        (res) => {
          if (res.statusCode === 301 || res.statusCode === 302) {
            httpsGet(res.headers.location, headers).then(resolve).catch(reject);
            return;
          }
          let body = "";
          res.on("data", (c) => (body += c));
          res.on("end", () => {
            if (res.statusCode !== 200) {
              reject(new Error(`HTTP ${res.statusCode} for ${url}\n${body.slice(0, 200)}`));
              return;
            }
            resolve(body);
          });
        }
      )
      .on("error", reject);
  });

function parseFrontmatterName(content) {
  const m = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return null;
  const nm = m[1].match(/^name:\s*(.+?)\s*$/m);
  return nm ? nm[1].trim() : null;
}

async function main() {
  console.log("Fetching gstack repo tree…");
  const tree = JSON.parse(
    await httpsGet(
      `https://api.github.com/repos/${OWNER}/${REPO}/git/trees/${BRANCH}?recursive=1`
    )
  );
  if (!tree.tree) {
    throw new Error(`Bad tree response: ${JSON.stringify(tree).slice(0, 200)}`);
  }

  const skillPaths = tree.tree
    .filter(
      (e) =>
        e.type === "blob" &&
        e.path.endsWith("/SKILL.md") &&
        !e.path.startsWith("test/") &&
        !e.path.endsWith(".tmpl") &&
        e.path !== "SKILL.md"
    )
    .map((e) => e.path);

  console.log(`Found ${skillPaths.length} candidate SKILL.md files.`);

  // Fetch in parallel batches to stay polite to raw.githubusercontent.com.
  const BATCH = 8;
  const results = [];
  for (let i = 0; i < skillPaths.length; i += BATCH) {
    const slice = skillPaths.slice(i, i + BATCH);
    const fetched = await Promise.all(
      slice.map(async (p) => {
        const raw = await httpsGet(
          `https://raw.githubusercontent.com/${OWNER}/${REPO}/${BRANCH}/${p}`
        );
        return { path: p, content: raw };
      })
    );
    results.push(...fetched);
    process.stdout.write(`  …${results.length}/${skillPaths.length}\r`);
  }
  console.log(`\nFetched ${results.length} skill files.`);

  // Dedupe by frontmatter name, skip reserved.
  const skills = [];
  const seen = new Set();
  const skipped = { noName: 0, reserved: 0, duplicate: 0 };
  for (const r of results) {
    const name = parseFrontmatterName(r.content);
    if (!name) { skipped.noName++; continue; }
    if (RESERVED_NAMES.has(name)) { skipped.reserved++; continue; }
    if (seen.has(name)) { skipped.duplicate++; continue; }
    seen.add(name);
    skills.push({ name, content: r.content, sourcePath: r.path });
  }
  skills.sort((a, b) => a.name.localeCompare(b.name));
  console.log(
    `Selected ${skills.length} skills. ` +
      `Skipped — noName: ${skipped.noName}, reserved: ${skipped.reserved}, duplicate: ${skipped.duplicate}.`
  );

  // Generate builtin-skills.ts (curated only) and gstack-skill-data.ts (gstack only).
  const localDir = "skills";
  const local = await loadLocalCuratedSkills(localDir);
  console.log(`Loaded ${local.length} local curated skills from ${localDir}/.`);

  const curatedTs = renderSkillsModule(
    local,
    "BUILTIN_SKILL_FILES",
    "Auto-generated by scripts/sync-gstack-skills.mjs — do not edit by hand.\n// Source: skills/ directory in this repo.\n// To refresh: run `node scripts/sync-gstack-skills.mjs`."
  );
  await fs.writeFile("src/builtin-skills.ts", curatedTs, "utf8");
  console.log(`Wrote src/builtin-skills.ts (${curatedTs.length.toLocaleString()} bytes, ${local.length} curated skills).`);

  const gstackTs = renderSkillsModule(
    skills,
    "GSTACK_SKILL_FILES",
    "Auto-generated by scripts/sync-gstack-skills.mjs — do not edit by hand.\n// Source: garrytan/gstack repo (MIT).\n// To refresh: run `node scripts/sync-gstack-skills.mjs`."
  );
  await fs.writeFile("src/gstack-skill-data.ts", gstackTs, "utf8");
  console.log(`Wrote src/gstack-skill-data.ts (${gstackTs.length.toLocaleString()} bytes, ${skills.length} gstack skills).`);
}

async function loadLocalCuratedSkills(dir) {
  const out = [];
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const ent of entries) {
    if (!ent.isDirectory()) continue;
    const skillFile = path.join(dir, ent.name, "SKILL.md");
    try {
      const content = await fs.readFile(skillFile, "utf8");
      const name = parseFrontmatterName(content) ?? ent.name;
      out.push({ name, content, sourcePath: skillFile });
    } catch {
      // skip folders without SKILL.md
    }
  }
  return out;
}

function renderSkillsModule(skills, exportName, comment) {
  const header = `// ${comment}

export const ${exportName}: Array<{ name: string; content: string }> = [
`;

  const body = skills
    .map(
      (s) =>
        `  {\n    name: ${JSON.stringify(s.name)},\n` +
        `    content: ${JSON.stringify(s.content)},\n  },`
    )
    .join("\n");

  return header + body + "\n];\n";
}

main().catch((e) => {
  console.error("sync-gstack-skills failed:", e);
  process.exit(1);
});
